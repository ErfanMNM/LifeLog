import com.example.ui.ScreenTab

@Composable
fun LifeLogBottomNav(
    currentTab: ScreenTab,
    onTabSelected: (ScreenTab) -> Unit
) {
    NavigationBar(
        windowInsets = WindowInsets.navigationBars,
        containerColor = MaterialTheme.colorScheme.surface,
        tonalElevation = 6.dp
    ) {
        val items = listOf(
            Triple(ScreenTab.DASHBOARD, Icons.Filled.Dashboard, Icons.Outlined.Dashboard),
            Triple(ScreenTab.TASKS, Icons.Filled.Assignment, Icons.Outlined.Assignment),
            Triple(ScreenTab.CALENDAR, Icons.Filled.CalendarMonth, Icons.Outlined.CalendarMonth),
            Triple(ScreenTab.NOTES, Icons.Filled.EditNote, Icons.Outlined.EditNote),
            Triple(ScreenTab.REMINDERS, Icons.Filled.Alarm, Icons.Outlined.Alarm),
            Triple(ScreenTab.TRIPS, Icons.Filled.Work, Icons.Outlined.Work)
        )

        items.forEach { (tab, filledIcon, outlinedIcon) ->
            val isSelected = currentTab == tab
            NavigationBarItem(
                selected = isSelected,
                onClick = { onTabSelected(tab) },
                icon = {
                    Icon(
                        imageVector = if (isSelected) filledIcon else outlinedIcon,
                        contentDescription = tab.title,
                        modifier = Modifier.size(22.dp)
                    )
                },
                label = {
                    Text(
                        text = tab.title,
                        fontSize = 10.sp,
                        maxLines = 1
                    )
                },
                colors = NavigationBarItemDefaults.colors(
                    selectedIconColor = MaterialTheme.colorScheme.onPrimaryContainer,
                    indicatorColor = MaterialTheme.colorScheme.primaryContainer,
                    unselectedIconColor = MaterialTheme.colorScheme.onSurfaceVariant,
                    unselectedTextColor = MaterialTheme.colorScheme.onSurfaceVariant
                ),
                modifier = Modifier.testTag("nav_item_${tab.name.lowercase()}")
            )
        }
    }
}
